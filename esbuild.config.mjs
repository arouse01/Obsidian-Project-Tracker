import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import path from 'node:path';
import 'dotenv/config';  // to output to different folder based on .env variable
import fs from 'node:fs';  // to copy manifest.json and styles.css to output folder
import { fileURLToPath } from 'node:url';  // to copy manifest.json and styles.css to output folder

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;
const vaultPath = process.env.OBSIDIAN_VAULT_FOLDER
if (!vaultPath) {
	throw new Error('OBSIDIAN_VAULT_PATH not set. Check the .env file.')
}
const outputDir = path.join(vaultPath, '.obsidian', 'plugins', 'IssueTracker')

const projectRoot = path.dirname(fileURLToPath(import.meta.url));

const copyPluginFiles = {
	name: 'copy-plugin-files',

	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length > 0) return;

			fs.mkdirSync(outputDir, { recursive: true });

			for (const file of ['manifest.json', 'styles.css']) {
				const source = path.join(projectRoot, file);
				const destination = path.join(outputDir, file);

				if (fs.existsSync(source)) {
					fs.copyFileSync(source, destination);
				} else if (file === 'manifest.json') {
					throw new Error(
						`Required plugin file not found: ${source}`
					);
				}
			}
		});
	},
};

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	plugins: [
		copyPluginFiles
	],
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outdir: outputDir,
	minify: prod,
});

for (const file of ['manifest.json', 'styles.css']) {
	const source = path.join('.', file);
	const dest = path.join(outputDir, file);
	if (fs.existsSync(source)) {
		fs.copyFileSync(source, dest)
	}
}

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}


for (const file of ['manifest.json', 'styles.css']) {
	fs.watchFile(
		path.join(projectRoot, file),
		{ interval: 500 },
		() => {
			const source = path.join(projectRoot, file);
			const destination = path.join(outputDir, file);

			if (fs.existsSync(source)) {
				fs.copyFileSync(source, destination);
				console.log(`Copied ${file}`);
			}
		}
	);
}

